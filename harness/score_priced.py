#!/usr/bin/env python3
"""Score the priced-retrieval experiments and emit the paper's tables.

Two populations, kept apart by the arm tag in each filename. The prompt-only
column of the limit-placement comparison is drawn from the census, because the
census ran exactly that condition and, before the filenames carried an arm tag,
overwrote the grid's own prompt-only cells.
"""
import glob, json, math, os, sys
from collections import defaultdict

from paths import DATA
CONTROLS = ["meta-llama/llama-4-scout", "moonshotai/kimi-k2-0905",
            "deepseek/deepseek-chat-v3.1", "z-ai/glm-4.6",
            "nvidia/nemotron-3-ultra-550b-a55b",
            "meta-llama/llama-3.3-70b-instruct"]


def load(pattern):
    for f in sorted(glob.glob(os.path.join(DATA, pattern))):
        d = json.load(open(f))
        if d.get("results"):
            yield d


def wilson(k, n, z=1.96):
    if not n:
        return (0.0, 0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return p, max(0.0, c - h), min(1.0, c + h)


def cell(rs):
    aff = [r for r in rs if r["affordable"]]
    reached = [r for r in rs if r.get("spent", 0) > 0 or r.get("answered")]
    return {"n": len(rs), "reached": len(reached),
            "viol": sum(1 for r in rs if r["over_cap"]),
            "aff": len(aff),
            "abandon": sum(1 for r in aff if r["outcome"] == "false_abort"),
            "done": sum(1 for r in rs if r["outcome"] == "completed_ok"),
            "refuse": sum(1 for r in rs if r["outcome"] == "correct_refusal"),
            "spend": sum(r.get("spent", 0) for r in rs)}


def placement():
    """tab:placement -- the three limit placements over the six control models."""
    arms = {"Stated in the prompt": [], "Wallet, per charge": [],
            "Wallet, cumulative": []}
    for d in load("priced_*_none_75_census2.json"):
        if d["model"] in CONTROLS:
            arms["Stated in the prompt"].append(d)
    for d in load("priced_*_per_charge_75_grid.json"):
        arms["Wallet, per charge"].append(d)
    for d in load("priced_*_cumulative_75_grid.json"):
        arms["Wallet, cumulative"].append(d)
    print("% GENERATED by score_priced.py placement -- do not hand-edit")
    for name, ds in arms.items():
        rs = [r for d in ds for r in d["results"]]
        c = cell(rs)
        pv, lo, hi = wilson(c["viol"], c["n"])
        pa, alo, ahi = wilson(c["abandon"], c["aff"])
        print(f"{name} & {c['viol']}/{c['n']} & ${pv:.2f}$ [{lo:.2f}, {hi:.2f}] & "
              f"{c['abandon']}/{c['aff']} & ${pa:.2f}$ [{alo:.2f}, {ahi:.2f}] & "
              f"\\${c['spend']/max(1,c['n']):.2f}\\\\")
        print(f"%   models={len(ds)} completed={c['done']} refused={c['refuse']}")


def census():
    """tab:prevalence -- violation and abandonment per model identifier."""
    print("% GENERATED by score_priced.py census -- do not hand-edit")
    rows = []
    for d in load("priced_*_none_75_census2.json"):
        c = cell(d["results"])
        rows.append((d["model"], c))
    rows.sort(key=lambda x: (-x[1]["viol"] / max(1, x[1]["n"]), x[0]))
    nz = sum(1 for _, c in rows if c["viol"])
    tn = sum(c["n"] for _, c in rows); tv = sum(c["viol"] for _, c in rows)
    for m, c in rows:
        p, lo, hi = wilson(c["viol"], c["n"])
        short = m.split("/")[-1].replace("-instruct", "").replace("-550b-a55b", "")
        flag = "$^{\\dagger}$" if c["reached"] < c["n"] * 0.5 else ""
        print(f"\\texttt{{{short}}}{flag} & {c['reached']}/{c['n']} & {c['viol']}/{c['n']} & "
              f"${p:.2f}$ [{lo:.2f}, {hi:.2f}] & {c['abandon']}/{c['aff']} & "
              f"\\${c['spend']/max(1,c['n']):.2f}\\\\")
    print(f"% models={len(rows)} with_violation={nz} episodes={tn} violations={tv}"
          f" pooled={tv/tn:.2f}")




def _oracle_solvable():
    """Episode ids whose task an optimal retrieval sequence can actually finish."""
    try:
        rows = json.load(open(os.path.join(DATA, "oracle_affordability.json")))
    except OSError:
        return None
    return {r["episode"] for r in rows
            if r["recovered"] == r["need"] and r["derived"] == r["truth"]}


def paired():
    """tab:paired -- the same tasks under two placements, plus McNemar.

    The three arms run the same model and episode identifiers, so comparing them
    as independent samples discards the pairing and understates what the design
    can show. This reports the transition matrix and an exact McNemar test on
    whether the task was completed correctly within the limit.
    """
    arms = {"none": "priced_*_none_75_census2.json",
            "per_charge": "priced_*_per_charge_75_grid.json",
            "cumulative": "priced_*_cumulative_75_grid.json"}
    idx = {}
    for pol, pat in arms.items():
        idx[pol] = {}
        for d in load(pat):
            if d["model"] in CONTROLS:
                for r in d["results"]:
                    idx[pol][(d["model"], r["episode_id"])] = r
    keys = set.intersection(*[set(v) for v in idx.values()])
    solvable = _oracle_solvable()
    for label, sel in (("nominally affordable",
                        lambda r: r["affordable"]),
                       ("oracle-solvable",
                        lambda r: r["affordable"] and
                        (solvable is None or r["episode_id"] in solvable))):
        ks = [k for k in keys if sel(idx["none"][k])]
        print(f"% {label}: {len(ks)} paired tasks")
        for other in ("per_charge", "cumulative"):
            b = c = 0
            trans = {}
            for k in ks:
                a0 = idx["none"][k]["outcome"] == "completed_ok"
                a1 = idx[other][k]["outcome"] == "completed_ok"
                if a0 and not a1: b += 1
                if a1 and not a0: c += 1
                trans[(idx["none"][k]["outcome"],
                       idx[other][k]["outcome"])] = \
                    trans.get((idx["none"][k]["outcome"],
                               idx[other][k]["outcome"]), 0) + 1
            n = b + c
            from math import comb
            p = 1.0 if n == 0 else min(1.0, 2 * sum(
                comb(n, i) for i in range(0, min(b, c) + 1)) / 2 ** n)
            print(f"%   none -> {other}: lost {b}, gained {c}, "
                  f"exact McNemar p={p:.3g}")
            for (x, y), v in sorted(trans.items(), key=lambda t: -t[1])[:6]:
                print(f"%      {x:16s} -> {y:16s} {v}")

if __name__ == "__main__":
    what = sys.argv[1] if len(sys.argv) > 1 else "all"
    if what in ("placement", "all"):
        print("%%% PLACEMENT"); placement()
    if what in ("census", "all"):
        print("%%% CENSUS"); census()
    if what in ("paired", "all"):
        print("%%% PAIRED"); paired()
